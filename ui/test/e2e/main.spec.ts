test("r2 creates one bot/conversation/cron and refreshes Cron without changing selection", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/")
  await page.getByRole("button", { name: "Criar bot" }).click()
  await page.getByLabel("Nome", { exact: true }).fill("seo-r2")
  await page.getByRole("dialog").getByRole("button", { name: "Avançado", exact: true }).click()
  await page.getByLabel("Função", { exact: true }).fill("SEO do site")
  await page.getByLabel("Título (opcional)").fill("Analista")
  await page.getByRole("dialog").getByRole("button", { name: "Criar bot", exact: true }).click()
  const bot = page.locator(".bot-entry").filter({ hasText: "seo-r2" })
  await expect(bot).toHaveCount(1)
  await expect(bot.locator(".bot-role")).toHaveText("SEO do site")
  await expect(bot.locator(".thread-row")).toHaveCount(1)
  const botId = await bot.locator(".tb-avatar").first().getAttribute("data-bot-id")
  if (!(await page.getByRole("button", { name: "Preview do projeto" }).isVisible()))
    await page.getByRole("button", { name: "Painel do bot", exact: true }).click()
  await page.getByRole("button", { name: "Preview do projeto" }).click()
  await expect(page.getByText("Nenhum projeto para seo-r2").first()).toBeVisible()
  await expect(page.locator(".preview-process-entry")).toHaveCount(0)
  await expect(page.locator(".preview-chat-feed")).toHaveText("Nenhuma mensagem nesta conversa.")
  await page.getByRole("button", { name: "Conectar", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Conectar projeto" })
  await expect(dialog.locator("input[type=checkbox]:checked")).toHaveCount(1)
  await expect(dialog.locator("label").filter({ has: page.locator("input[type=checkbox]:checked") })).toContainText(
    "seo-r2",
  )
  await dialog.getByRole("button", { name: "Fechar diálogo" }).click()
  await page.getByRole("button", { name: "Voltar ao chat" }).click()
  await showBotRoutines(page, "seo-r2")
  await page.getByRole("button", { name: /Criar rotina/ }).click()
  await expect(page.getByRole("combobox", { name: "Bot", exact: true })).toHaveValue(botId ?? "missing")
  await page.getByLabel("Nome", { exact: true }).fill("SEO semanal r2")
  await page.getByLabel("Prompt", { exact: true }).fill("Liste as rotas")
  await page.getByRole("button", { name: "Salvar rotina" }).click()
  await expect(page.locator(".routine-item").filter({ hasText: "SEO semanal r2" })).toHaveCount(1)
  await page.getByRole("button", { name: "Atualizar", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Rotinas" })).toBeVisible()
  await expect(page.locator(".routine-item").filter({ hasText: "SEO semanal r2" })).toHaveCount(1)
  await page.getByRole("button", { name: /^Bots/ }).click()
  await expect(page.getByRole("textbox", { name: "Mensagem para seo-r2" })).toBeVisible()
  await expect(bot.locator(".thread-row")).toHaveCount(1)
})
