import AxeBuilder from "@axe-core/playwright"
import { expect, test } from "@playwright/test"

test.use({ channel: "chromium", viewport: { width: 390, height: 844 }, reducedMotion: "reduce" })

test("phone navigation traps focus and reaches conversations, search, creation and notifications", async ({ page }) => {
  await page.goto("/test/e2e/home-harness.html")
  await expect(page.getByRole("textbox", { name: "Mensagem para mark" })).toBeVisible()
  const menu = page.getByRole("button", { name: "Abrir menu" })
  const drawer = page.getByRole("dialog", { name: "Barra lateral" })
  await expect(menu).toBeInViewport()
  const menuBounds = await menu.boundingBox()
  const identityBounds = await page.locator(".chat-bot-chip").boundingBox()
  expect(menuBounds && identityBounds && menuBounds.x + menuBounds.width <= identityBounds.x).toBeTruthy()
  await expect(page.getByRole("navigation", { name: "Barra lateral" })).toHaveCount(0)
  await menu.click()
  await expect(drawer).toBeVisible()
  await expect(drawer.getByRole("button", { name: "Fechar menu" })).toBeFocused()
  // The browser owns the modal focus trap and makes the underlying workspace inert.
  await page
    .getByRole("textbox", { name: "Mensagem para mark", includeHidden: true })
    .evaluate((element) => element.focus())
  expect(await drawer.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  await drawer.getByRole("button", { name: "Buscar conversas" }).focus()
  await page.keyboard.press("Shift+Tab")
  expect(await drawer.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  await drawer.getByRole("button", { name: /^Avançado(?: Ajustes deste bot)?$/ }).focus()
  await page.keyboard.press("Tab")
  await expect(drawer.getByRole("button", { name: "Buscar conversas" })).toBeFocused()
  const accessibility = await new AxeBuilder({ page }).analyze()
  expect(accessibility.violations.filter((item) => ["serious", "critical"].includes(item.impact ?? ""))).toEqual([])
  await page.screenshot({ path: "test-results/mobile-navigation-drawer.png" })

  await drawer.getByRole("button", { name: "Nova conversa", exact: true }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.locator('[data-message-id="m2"]')).toHaveCount(0)
  await menu.click()
  await drawer.getByRole("button", { name: /Campaign review/ }).click()
  await expect(drawer).not.toBeVisible()
  await expect(menu).toBeFocused()
  await expect(page.locator('[data-message-id="m2"]')).toBeVisible()

  await menu.click()
  await drawer.locator('[data-bot-entry="bot-onb"] .bot-row-main').click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole("textbox", { name: "Mensagem para onb" })).toBeVisible()

  await menu.click()
  await drawer.getByRole("button", { name: "Buscar conversas" }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole("combobox", { name: "Buscar bots, conversas e configurações" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(menu).toBeFocused()

  await menu.click()
  await drawer.getByRole("button", { name: "Criar bot", exact: true }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole("dialog", { name: "Criar um bot" })).toBeVisible()
  await expect(page.getByLabel("Nome", { exact: true })).toBeFocused()
  await page.getByRole("button", { name: "Fechar diálogo" }).click()
  await expect(menu).toBeFocused()

  await menu.click()
  await drawer.getByRole("button", { name: /^Notificações/ }).click()
  const notifications = drawer.getByRole("region", { name: "Central de notificações" })
  await expect(notifications).toBeVisible()
  await notifications.getByRole("button", { name: "Abrir", exact: true }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole("textbox", { name: "Mensagem para mark" })).toBeVisible()

  await menu.click()
  await page.keyboard.press("Escape")
  await expect(drawer).not.toBeVisible()
  await expect(menu).toBeFocused()
  await menu.click()
  await page.mouse.click(375, 400)
  await expect(drawer).not.toBeVisible()
  await expect(menu).toBeFocused()
})

test("menu remains available on global pages and desktop keeps its sidebar", async ({ page }) => {
  await page.goto("/test/e2e/home-harness.html")
  const menu = page.getByRole("button", { name: "Abrir menu" })
  const drawer = page.getByRole("dialog", { name: "Barra lateral" })
  await menu.click()
  await drawer.getByRole("button", { name: /^Avançado(?: Ajustes deste bot)?$/ }).click()
  await drawer.getByRole("button", { name: "MCP", exact: true }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole("heading", { name: "MCP", exact: true })).toBeVisible()
  await expect(menu).toBeInViewport()
  await menu.click()
  await drawer.getByRole("button", { name: /^Bots/ }).click()
  await expect(page.getByRole("textbox", { name: "Mensagem para mark" })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(menu).toHaveCount(0)
  const sidebar = page.getByRole("navigation", { name: "Barra lateral" })
  await expect(sidebar).toBeVisible()
  await expect(sidebar).toHaveCSS("width", "320px")
  await expect(sidebar.getByRole("button", { name: "Fechar menu" })).toHaveCount(0)
})
