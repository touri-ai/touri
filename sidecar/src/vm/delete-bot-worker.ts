import { botDeletionRecordTasks } from "./delete-bot-records"

// The deletion worker owns bounded SQLite transactions so a slow FTS trigger
// cannot delay HTTP, streaming or turns on the server thread.
export const deleteBotWorkerSource = [
  'import { Database, constants } from "bun:sqlite";',
  "",
  "let database;",
  "let stopped = false;",
  "let checkpointDue = true;",
  "let committedUnits = 0;",
  "let checkpointWaitStarted = 0;",
  "const REPLAY_LIMIT = 1;",
  "const MESSAGE_LIMIT = 1;",
  "const TRANSCRIPT_LIMIT = 1;",
  `const RECORD_TASKS = ${JSON.stringify(botDeletionRecordTasks)};`,
  "",
  'const isBusy = (error) => typeof error?.code === "string" &&',
  '  (error.code.startsWith("SQLITE_BUSY") || error.code.startsWith("SQLITE_LOCKED"));',
  'const getSqliteCode = (error) => typeof error?.code === "string" && error.code.startsWith("SQLITE_") ? error.code : undefined;',
  "",
  "const collectAttachments = (value, ids) => {",
  '  if (!value || typeof value !== "object") return;',
  "  Object.entries(value).forEach(([key, item]) => {",
  '    if ((key === "attachmentId" || key === "outputAttachmentId") && typeof item === "string") ids.add(item);',
  '    else if (item && typeof item === "object") collectAttachments(item, ids);',
  "  });",
  "};",
  "",
  "const finishCheckpoint = () => {",
  '  const result = database.query("PRAGMA wal_checkpoint(PASSIVE)").get();',
  "  if (result.busy || result.checkpointed < result.log) return false;",
  "  checkpointDue = false;",
  "  committedUnits = 0;",
  "  checkpointWaitStarted = 0;",
  "  return true;",
  "};",
  "",
  "const isOwnedThread = (botId, threadId) => Boolean(database.query(",
  '  "SELECT 1 FROM threads WHERE id = ? AND bot_id = ? LIMIT 1",',
  ").get(threadId, botId));",
  "",
  "const isOwnedProcess = (botId, processId) => Boolean(database.query(",
  '  "SELECT 1 FROM processes WHERE id = ? AND vm_bot_id = ? LIMIT 1",',
  ").get(processId, botId));",
  "",
  "const isOwnedTab = (botId, tabId) => Boolean(database.query(",
  '  "SELECT 1 FROM browser_tabs WHERE id = ? AND owner_bot_id = ? LIMIT 1",',
  ").get(tabId, botId));",
  "",
  'const eventReferencesBot = (value, botId, path = "$") => {',
  '  if (!value || typeof value !== "object") return false;',
  "  for (const [key, item] of Object.entries(value)) {",
  '    const nextPath = path + "." + key;',
  '    if (["botId", "bot_id", "ownerBotId", "vmBotId"].includes(key) && item === botId) return true;',
  '    if (["threadId", "thread_id", "sourceThreadId", "groupThreadId"].includes(key) &&',
  '        typeof item === "string" && isOwnedThread(botId, item)) return true;',
  '    if (key === "processId" && typeof item === "string" && isOwnedProcess(botId, item)) return true;',
  '    if (key === "tabId" && typeof item === "string" && isOwnedTab(botId, item)) return true;',
  '    if (nextPath === "$.bot.id" && item === botId) return true;',
  '    if (nextPath === "$.thread.id" && typeof item === "string" && isOwnedThread(botId, item)) return true;',
  '    if (nextPath === "$.spec.id" && typeof item === "string" && isOwnedProcess(botId, item)) return true;',
  '    if (item && typeof item === "object" && eventReferencesBot(item, botId, nextPath)) return true;',
  "  }",
  "  return false;",
  "};",
  "",
  "const saveAttachmentCandidates = (botId, ids) => {",
  "  if (!ids.size) return;",
  "  const insert = database.query(",
  '    "INSERT OR IGNORE INTO bot_deletion_attachments(bot_id, attachment_id) VALUES (?, ?)",',
  "  );",
  "  ids.forEach((id) => insert.run(botId, id));",
  "};",
  "",
  "const saveProgress = (botId, patch) => {",
  "  database.query(`UPDATE bot_deletions SET error_code = NULL, phase = coalesce(?, phase), cursor = coalesce(?, cursor),",
  "    high_water = coalesce(?, high_water), attachment_page = coalesce(?, attachment_page),",
  "    processed = processed + ?, updated_at = ? WHERE bot_id = ?`).run(",
  "    patch.phase ?? null,",
  "    patch.cursor ?? null,",
  "    patch.highWater ?? null,",
  "    patch.attachmentPage ?? null,",
  "    patch.processed ?? 0,",
  "    Date.now(),",
  "    botId,",
  "  );",
  "};",
  "",
  "const processReplayBatch = (job) => {",
  "  const highWater = job.high_water || Number(database.query(",
  '    "SELECT coalesce(max(seq), 0) AS seq FROM ui_event_log",',
  "  ).get().seq);",
  "  const rows = database.query(`SELECT seq, event_json FROM ui_event_log",
  "    WHERE seq > ? AND seq <= ? ORDER BY seq LIMIT ?`).all(job.cursor, highWater, REPLAY_LIMIT);",
  "  if (!rows.length) {",
  '    saveProgress(job.bot_id, { phase: "messages", cursor: 0, highWater: 0 });',
  "    return;",
  "  }",
  "",
  "  const attachments = new Set();",
  "  const deleted = rows.flatMap((row) => {",
  "    const event = JSON.parse(row.event_json);",
  "    if (!eventReferencesBot(event, job.bot_id)) return [];",
  "    collectAttachments(event, attachments);",
  "    return [row.seq];",
  "  });",
  "  saveAttachmentCandidates(job.bot_id, attachments);",
  "  const lastSeq = rows[rows.length - 1].seq;",
  "  if (deleted.length) {",
  "    // The replay floor can already exceed every row in this deletion batch.",
  "    database.exec(`INSERT INTO schema_meta(key,value) VALUES('event_retention_revision','1')",
  "      ON CONFLICT(key) DO UPDATE SET value=CAST(value AS INTEGER)+1`);",
  '    database.query("UPDATE transcript_maintenance SET ui_delete_before_seq = ? WHERE id = 1").run(lastSeq);',
  '    const placeholders = deleted.map(() => "?").join(",");',
  '    database.query("DELETE FROM ui_event_log WHERE seq IN (" + placeholders + ")").run(...deleted);',
  "    database.query(`UPDATE schema_meta SET value = cast(max(cast(value AS INTEGER), ?) AS TEXT)",
  "      WHERE key = 'ui_event_floor_seq'`).run(Math.max(...deleted));",
  '    database.exec("UPDATE transcript_maintenance SET ui_delete_before_seq = 0 WHERE id = 1");',
  "  }",
  "  saveProgress(job.bot_id, { cursor: lastSeq, highWater, processed: rows.length });",
  "};",
  "",
  "const processMessageBatch = (job) => {",
  "  const rows = database.query(`SELECT thread_id, id, parts_json FROM messages",
  "    WHERE thread_id IN (SELECT id FROM threads WHERE bot_id = ?)",
  "    ORDER BY thread_id, id LIMIT ?`).all(job.bot_id, MESSAGE_LIMIT);",
  "  if (!rows.length) {",
  "    const highWater = Number(database.query(",
  '      "SELECT coalesce(max(id), 0) AS id FROM transcript_entries",',
  "    ).get().id);",
  '    saveProgress(job.bot_id, { phase: "transcript", cursor: 0, highWater });',
  "    return;",
  "  }",
  "",
  "  const attachments = new Set();",
  "  rows.forEach((row) => collectAttachments(JSON.parse(row.parts_json), attachments));",
  "  saveAttachmentCandidates(job.bot_id, attachments);",
  '  const values = rows.map(() => "(?, ?)").join(",");',
  "  const parameters = rows.flatMap((row) => [row.thread_id, row.id]);",
  '  database.query("DELETE FROM messages WHERE (thread_id, id) IN (VALUES " + values + ")").run(...parameters);',
  "  saveProgress(job.bot_id, { processed: rows.length });",
  "};",
  "",
  "const processTranscriptBatch = (job) => {",
  "  const rows = database.query(`SELECT id, thread_id, event_json FROM transcript_entries",
  "    WHERE id > ? AND id <= ? ORDER BY id LIMIT ?`).all(job.cursor, job.high_water, TRANSCRIPT_LIMIT);",
  "  if (!rows.length) {",
  '    saveProgress(job.bot_id, { phase: "attachments", cursor: 0, highWater: 0 });',
  "    return;",
  "  }",
  "",
  "  const attachments = new Set();",
  "  const deleted = rows.flatMap((row) => {",
  "    if (!isOwnedThread(job.bot_id, row.thread_id)) return [];",
  "    collectAttachments(JSON.parse(row.event_json), attachments);",
  "    return [row.id];",
  "  });",
  "  saveAttachmentCandidates(job.bot_id, attachments);",
  "  const lastId = rows[rows.length - 1].id;",
  "  if (deleted.length) {",
  '    database.query("UPDATE transcript_maintenance SET delete_before_id = ? WHERE id = 1").run(lastId);',
  '    const placeholders = deleted.map(() => "?").join(",");',
  '    database.query("DELETE FROM transcript_entries WHERE id IN (" + placeholders + ")").run(...deleted);',
  '    database.exec("UPDATE transcript_maintenance SET delete_before_id = 0 WHERE id = 1");',
  "  }",
  "  saveProgress(job.bot_id, { cursor: lastId, processed: rows.length });",
  "};",
  "",
  "const processAttachmentBatch = (job) => {",
  "  const rows = database.query(`SELECT attachment_id FROM bot_deletion_attachments",
  "    WHERE bot_id = ? ORDER BY attachment_id LIMIT ?`).all(job.bot_id, 50);",
  "  if (!rows.length) {",
  '    saveProgress(job.bot_id, { phase: "records:0", cursor: 0, highWater: 0 });',
  "    return;",
  "  }",
  "",
  "  const page = job.attachment_page;",
  '  const key = "storage.deleted-attachments:" + job.bot_id + ":" + page;',
  "  const ids = rows.map((row) => row.attachment_id);",
  "  database.query(`INSERT INTO settings(key, value_json, updated_at) VALUES (?, ?, ?)",
  "    ON CONFLICT(key) DO UPDATE SET value_json = excluded.value_json, updated_at = excluded.updated_at`).run(",
  "    key,",
  "    JSON.stringify(ids),",
  "    Date.now(),",
  "  );",
  '  const placeholders = ids.map(() => "?").join(",");',
  '  database.query("DELETE FROM bot_deletion_attachments WHERE bot_id = ? AND attachment_id IN (" + placeholders + ")")',
  "    .run(job.bot_id, ...ids);",
  "  saveProgress(job.bot_id, { attachmentPage: page + 1, processed: ids.length });",
  "};",
  "",
  "const processRecordBatch = (job) => {",
  '  const index = Number(job.phase.slice("records:".length));',
  "  const task = RECORD_TASKS[index];",
  '  if (!task) throw new Error("Unknown deletion phase");',
  '  const highWater = job.high_water || Number(database.query("SELECT coalesce(max(rowid), 0) AS id FROM " + task.table).get().id);',
  '  const rows = database.query("SELECT rowid AS id FROM " + task.table +',
  '    " WHERE rowid > ? AND rowid <= ? ORDER BY rowid LIMIT 4").all(job.cursor, highWater);',
  "  if (!rows.length) {",
  '    const phase = index + 1 < RECORD_TASKS.length ? "records:" + (index + 1) : "finalize";',
  "    saveProgress(job.bot_id, { phase, cursor: 0, highWater: 0 });",
  "    return;",
  "  }",
  "",
  '  const action = task.update ? "UPDATE " + task.table + " SET " + task.update : "DELETE FROM " + task.table;',
  '  const statement = database.query(action + " WHERE rowid = ?1 AND (" + task.predicate + ")");',
  "  rows.forEach((row) => statement.run(row.id, job.bot_id));",
  "  saveProgress(job.bot_id, { cursor: rows[rows.length - 1].id, highWater, processed: rows.length });",
  "};",
  "",
  "const processBatch = (botId) => {",
  '  const job = database.query("SELECT * FROM bot_deletions WHERE bot_id = ?").get(botId);',
  '  if (!job) return { done: true, phase: "done", processed: 0 };',
  '  if (job.phase === "replay") processReplayBatch(job);',
  '  if (job.phase === "messages") processMessageBatch(job);',
  '  if (job.phase === "transcript") processTranscriptBatch(job);',
  '  if (job.phase === "attachments") processAttachmentBatch(job);',
  '  if (job.phase.startsWith("records:")) processRecordBatch(job);',
  '  const next = database.query("SELECT phase, processed, error_code FROM bot_deletions WHERE bot_id = ?").get(botId);',
  '  return { done: next?.phase === "finalize", phase: next?.phase ?? "done", processed: next?.processed ?? 0 };',
  "};",
  "",
  "self.onmessage = async ({ data }) => {",
  '  if (data.type === "start") {',
  "    try {",
  "      database = new Database(data.filename, constants.SQLITE_OPEN_READWRITE | constants.SQLITE_OPEN_NOFOLLOW);",
  // Checkpoints run between write transactions so a commit never monopolizes the writer lock.
  '      database.exec("PRAGMA busy_timeout = 0; PRAGMA journal_mode = WAL; PRAGMA synchronous = NORMAL; PRAGMA foreign_keys = ON; PRAGMA wal_autocheckpoint = 0; PRAGMA cache_size = -65536");',
  '      self.postMessage({ type: "ready" });',
  "    } catch (error) {",
  '      self.postMessage({ type: "startup-error", busy: isBusy(error) });',
  "    }",
  "    return;",
  "  }",
  '  if (data.type === "stop") {',
  "    stopped = true;",
  "    database?.close();",
  "    database = undefined;",
  "    self.close();",
  "    return;",
  "  }",
  '  if (stopped || !database || data.type !== "batch") return;',
  "  try {",
  "    // Pause the producer behind readers instead of growing its WAL without a bound.",
  "    if (checkpointDue && !finishCheckpoint()) {",
  "      checkpointWaitStarted ||= performance.now();",
  '      if (performance.now() - checkpointWaitStarted >= 5000) throw Object.assign(new Error("Checkpoint deferred"), { code: "SQLITE_BUSY" });',
  "      await new Promise((resolve) => setTimeout(resolve, 10));",
  "      if (stopped) return;",
  '      const job = database.query("SELECT phase, processed FROM bot_deletions WHERE bot_id = ?").get(data.botId);',
  '      self.postMessage({ type: "batch", id: data.id, result: { done: !job || job.phase === "finalize", phase: job?.phase ?? "done", processed: job?.processed ?? 0 } });',
  "      return;",
  "    }",
  "    const started = performance.now();",
  "    let result;",
  "    // Commit and release the lock before every task yield; only IPC replies are coalesced.",
  "    for (let unit = 0; unit < 16 && !stopped; unit++) {",
  "      result = database.transaction(() => processBatch(data.botId)).immediate();",
  "      committedUnits += 1;",
  "      if (committedUnits >= 128) checkpointDue = true;",
  "      if (result.done || checkpointDue || performance.now() - started >= 8) break;",
  "      await new Promise((resolve) => setImmediate(resolve));",
  "    }",
  "    if (stopped) return;",
  '    self.postMessage({ type: "batch", id: data.id, result });',
  "  } catch (error) {",
  "    if (stopped) return;",
  '    self.postMessage({ type: "batch-error", id: data.id, busy: isBusy(error), code: getSqliteCode(error) });',
  "  }",
  "};",
].join("\n")
